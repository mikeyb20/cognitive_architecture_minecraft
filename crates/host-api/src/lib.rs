//! World and host interface (spec §2).
//!
//! The brain cannot tell which world it is in: the Rust sim and the Mineflayer
//! adapter both implement [`World`] and [`Host`]. Multi-agent support is in the
//! types from day one ([`AgentId`]), even though this phase runs single agents.

use serde::{Deserialize, Serialize};

pub mod command;
pub mod craft;
pub mod link;
pub mod ontology;
pub mod planner;
pub mod reflex;

pub use ontology::{Skill, TaskType};

/// Identifies one agent (one body) in a world.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AgentId(pub u32);

/// Identifies a perceivable "thing" (tile/block type, entity type, region, recipe)
/// for novelty and memory (spec §5).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct ThingId(pub String);

/// Block or tile position.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Pos {
    pub x: i32,
    pub y: i32,
    pub z: i32,
}

/// Item name (Minecraft naming, shared by both worlds) and count.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Inventory {
    pub items: Vec<(String, u32)>,
}

impl Inventory {
    /// Total count of one item.
    pub fn count(&self, item: &str) -> u32 {
        self.items
            .iter()
            .filter(|(name, _)| name == item)
            .map(|(_, n)| n)
            .sum()
    }
}

/// Something perceived this tick.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Seen {
    pub thing: ThingId,
    pub kind: SeenKind,
    pub pos: Pos,
    pub distance: f32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub enum SeenKind {
    Block,
    Entity { hostile: bool },
    Player,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct ChatMsg {
    pub from: String,
    pub text: String,
}

/// What a candidate action is aimed at.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub enum Target {
    Pos(Pos),
    Thing(ThingId),
    Item(String),
    Player(String),
}

/// One agent's view of the world for one tick (spec §2).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Observation {
    pub agent: AgentId,
    pub tick: u64,
    /// 0..1 through the day; night is >= 0.5.
    pub day_phase: f32,
    /// 0..1
    pub health: f32,
    /// 0..1
    pub food: f32,
    pub position: Pos,
    pub inventory: Inventory,
    pub visible: Vec<Seen>,
    pub chat: Vec<ChatMsg>,
    pub damage_taken: f32,
    /// In bed or otherwise safely resting.
    pub resting: bool,
    /// Enclosed so hostile mobs cannot reach the agent.
    pub sheltered: bool,
}

impl Observation {
    /// Night is the second half of the day (spec §21).
    pub fn is_night(&self) -> bool {
        self.day_phase >= 0.5
    }

    /// Distance to the nearest hostile entity, if any is visible.
    pub fn nearest_hostile(&self) -> Option<f32> {
        self.visible
            .iter()
            .filter(|s| matches!(s.kind, SeenKind::Entity { hostile: true }))
            .map(|s| s.distance)
            .min_by(f32::total_cmp)
    }
}

/// An external action the host offers (spec §2, §6). Internal actions are
/// generated by the brain, not the host.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Candidate {
    pub id: u32,
    pub skill: Skill,
    pub target: Option<Target>,
    /// One of the 7 tenacity task types (#36).
    pub task_type: TaskType,
    /// Host estimate, 0..1.
    pub est_cost: f32,
    /// Host estimate, 0..1.
    pub est_risk: f32,
    /// Step of a player command; gets the external-drive floor (spec §16, #41).
    pub commanded: bool,
}

/// How hard to carry out an action (spec §11, §16).
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Intensity {
    /// g(C), or max(g(C), eps_ext * (1 - D)) for commanded steps.
    pub effort: f32,
    /// 1 - execution loss from choking (sim only, #43).
    pub focus: f32,
    pub external_drive: bool,
}

/// Result of executing a candidate.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Outcome {
    pub success: bool,
    /// 0..1 progress on the step.
    pub progress: f32,
    pub items_gained: Inventory,
    pub damage: f32,
    pub new_things: Vec<ThingId>,
    pub blocked: bool,
    pub duration_ticks: u32,
}

/// A named scenario from `configs/scenarios/` (spec §21, §26).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct Scenario {
    pub name: String,
}

/// Most external candidates a host offers per decision (spec §6: K = 20).
pub const MAX_CANDIDATES: usize = 20;

/// One run's world, shared by all agents (spec §2).
pub trait World {
    fn reset(&mut self, seed: u64, scenario: &Scenario);
    /// Advance time, mobs and day/night.
    fn step_world(&mut self, ticks: u32);
    fn host(&mut self, agent: AgentId) -> &mut dyn Host;
}

/// One agent's body in a world (spec §2).
pub trait Host {
    fn perceive(&mut self) -> Observation;
    /// External candidates only, at most K = 20 (spec §6).
    fn candidate_actions(&mut self, obs: &Observation) -> Vec<Candidate>;
    fn execute(&mut self, action: &Candidate, intensity: Intensity) -> Outcome;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn inventory_count_sums_stacks() {
        let inv = Inventory {
            items: vec![
                ("oak_log".into(), 3),
                ("dirt".into(), 5),
                ("oak_log".into(), 2),
            ],
        };
        assert_eq!(inv.count("oak_log"), 5);
        assert_eq!(inv.count("stone"), 0);
    }

    #[test]
    fn observation_round_trips_through_json() {
        let obs = Observation {
            agent: AgentId(0),
            tick: 42,
            day_phase: 0.25,
            health: 1.0,
            food: 0.8,
            position: Pos::default(),
            inventory: Inventory::default(),
            visible: vec![],
            chat: vec![],
            damage_taken: 0.0,
            resting: false,
            sheltered: false,
        };
        let json = serde_json::to_string(&obs).unwrap();
        let back: Observation = serde_json::from_str(&json).unwrap();
        assert_eq!(obs, back);
    }
}
